// Writes docs/ASSET_LICENSES.md from the two provenance records, so the document cannot
// drift from what the pipelines actually produced.
//
//   node scripts/asset-licenses.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const wallpapers = JSON.parse(readFileSync('docs/wallpapers.json', 'utf8'));
const marks = JSON.parse(readFileSync('docs/brand-marks.json', 'utf8'));
const kb = bytes => `${Math.round(bytes / 1024)} kB`;
const packBytes = wallpapers.reduce((sum, w) => sum + w.production.bytes + w.preview.bytes, 0);

const lines = [];
const add = (...text) => lines.push(...text);

add(
    '# Third-party assets and licences',
    '',
    'Generated by `scripts/asset-licenses.mjs` from `docs/wallpapers.json` and `docs/brand-marks.json`.',
    'Edit the pipelines, not this file.',
    '',
    'Everything listed here is packaged inside the extension. Nothing is fetched from a third',
    'party at run time for these assets.',
    '',
    '## 1. Photographic wallpapers',
    '',
    `Eight photographs, all released by their creators under **CC0 1.0 Universal (Public Domain`,
    `Dedication)**. For every file, both the Wikimedia Commons file page and the Commons API`,
    `licence metadata were checked before download (\`scripts/wallpapers-fetch.mjs\` refuses to`,
    `download otherwise). CC0 does not require attribution; creator and source are recorded anyway.`,
    '',
    `- Licence text: https://creativecommons.org/publicdomain/zero/1.0/`,
    `- Attribution required: **no**`,
    `- Pack size in the package: **${(packBytes / 1024 / 1024).toFixed(2)} MB** (full images + gallery previews); budget 3.5 MB, enforced by \`scripts/size.mjs\``,
    `- Originals and downloaded renditions are not in the repository or the package.`,
    '',
);
for (const w of wallpapers) {
    add(
        `### ${w.name} (\`${w.production.file}\`)`,
        '',
        `| | |`,
        `|---|---|`,
        `| Creator | ${w.creator} |`,
        `| Source | ${w.source} |`,
        `| Original title | ${w.title} |`,
        `| Licence | ${w.license} — ${w.licenseUrl} |`,
        `| Licence verified | ${w.licenseVerified} |`,
        `| Attribution required | No |`,
        `| Date acquired | ${w.acquired} |`,
        `| Original | ${w.original.width}×${w.original.height}, ${(w.original.bytes / 1e6).toFixed(1)} MB |`,
        `| Downloaded rendition | ${kb(w.download.bytes)} (JPEG, ~2560 px wide) |`,
        `| Production file | ${w.production.width}×${w.production.height}, ${kb(w.production.bytes)}, WebP quality ${w.production.quality} |`,
        `| Gallery preview | \`${w.preview.file}\`, ${w.preview.width}×${w.preview.height}, ${kb(w.preview.bytes)} |`,
        `| Modifications | ${w.modifications} |`,
        '',
    );
}

add(
    '## 2. Brand marks for starter apps',
    '',
    `Source: **${marks.package}** (https://simpleicons.org), extracted on ${marks.generated} by`,
    '`scripts/brand-marks.mjs`. The package is a development dependency only; just the files',
    'listed below are copied into the extension (`marks/*.svg`).',
    '',
    'An individual brand-usage review was done on ' + marks.reviewed + ' for all 41 marks first bundled.',
    'Rule applied: a mark stays only if its owner\'s own published guidance allows (a) using the',
    'mark to link or refer to the service without asking first and (b) showing it in black or',
    'white. Where guidance was strict, missing, unreadable or unclear, the mark was removed and',
    'the app uses its site icon or a letter. **' + marks.bundled.length + ' kept, ' + marks.removedAfterReview.length + ' removed.**',
    '',
    '- The Simple Icons collection is CC0-1.0; that does not make each mark CC0. None of the kept',
    '  entries declares a licence that conflicts.',
    '- Every mark is a trademark of its owner, used only to identify a link to that owner\'s own',
    '  service, at icon size, next to its name. No endorsement or affiliation is implied.',
    '- Treatment: shape unaltered, painted near-white on dark themes and near-black on light',
    '  themes, never tinted.',
    '- This is a reading of public guidance, not legal advice. Removing a mark is a two-line change',
    '  (`scripts/brand-marks.mjs` and `LOCAL_MARKS` in `src/core/icons.ts`).',
    '',
    '### Kept',
    '',
    '| Starter app | File | Basis (owner\'s guidance) |',
    '|---|---|---|',
    ...marks.bundled.map(m => `| ${m.app} | \`marks/${m.slug}.svg\` | ${m.basis} |`),
    '',
    '### Removed after review',
    '',
    '| Starter app | Why |',
    '|---|---|',
    ...marks.removedAfterReview.map(e => `| ${e.app} | ${e.reason} |`),
    '',
    '### Never bundled',
    '',
    '| Starter app | Reason |',
    '|---|---|',
    ...marks.excluded.map(e => `| ${e.app} | ${e.reason} |`),
    '',
    '## 3. Not packaged',
    '',
    '- No fonts are shipped (system font stacks only).',
    '- Icons for Google apps are requested from Google\'s own static host when online; they are not',
    '  copied into the package.',
    '- Interface glyphs (Space and toolbar icons) are drawn for this project.',
    '',
);
writeFileSync('docs/ASSET_LICENSES.md', lines.join('\n'));
console.log(`docs/ASSET_LICENSES.md written: ${wallpapers.length} wallpapers, ${marks.bundled.length} marks kept, ${marks.removedAfterReview.length} removed`);
